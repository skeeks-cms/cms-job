namespace skeeks\cms\job\transport;

use yii\base\BaseObject;

/**
 * Параметры процесса-воркера.
 *
 * Принадлежат пакету, а не библиотеке очередей: набор опций публичной команды
 * `cms-job/worker` не должен меняться при смене транспорта.
 *
 * Количество воркеров здесь отсутствует намеренно — это ответственность
 * Supervisor, systemd, Docker или Kubernetes, а не базы приложения.
 */
class WorkerOptions extends BaseObject
{
    /**
     * @var string Имя полосы. Один процесс слушает ровно одну полосу.
     */
    public $queue;

    /**
     * @var bool Выйти, когда очередь опустеет, вместо ожидания новых сообщений.
     */
    public $once = false;

    /**
     * @var int Сколько секунд ждать сообщение в одном опросе.
     */
    public $timeout = 3;

    /**
     * @var int Остановиться после этого числа обработанных сообщений. 0 — без предела.
     */
    public $maxJobs = 0;

    /**
     * @var int Остановиться, когда потребление памяти превысит это значение, МиБ.
     *          0 — без предела. Плановый перезапуск дешевле утечки.
     */
    public $memoryLimit = 0;

    /**
     * @var int Остановиться после этого числа секунд работы. 0 — без предела.
     */
    public $maxRuntime = 0;

    /**
     * @var bool Печатать ход обработки.
     */
    public $verbose = false;

    /**
     * @var bool Выполнять каждое задание в дочернем процессе.
     *
     * По умолчанию включено. Изоляция даёт три вещи, недостижимые в одном
     * процессе: фатальная ошибка обработчика не уносит воркер, память не
     * накапливается между заданиями, и TTR соблюдается жёстко, не полагаясь на
     * добросовестность обработчика.
     *
     * Выключать имеет смысл для отладки, когда нужны точки останова и
     * профилировщик в том же процессе.
     */
    public $isolate = true;

    /**
     * @var string|null Идентификатор процесса в журнале и в строке запуска.
     */
    public $workerId;
}
